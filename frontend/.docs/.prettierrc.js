// ============================================================
//                     Prettier 完整配置参考
// ============================================================
//  本文件列出了 Prettier 所有可配置选项及其详细说明。
//  默认值即为 Prettier 开箱即用的行为，可按需修改。
//  支持的文件格式：JSON / JSON5 / YAML / TOML / JS Module
// ============================================================

module.exports = {
  // ----------------------------------------------------------
  // 1. printWidth  ——  单行最大字符数
  // ----------------------------------------------------------
  //  Prettier 会尝试将代码行限制在此宽度内。
  //  并非所有行都能被精确换行，但 Prettier 会尽力而为。
  //  默认值：80
  //  适用场景：团队协作时建议统一，通常 80~120。
  printWidth: 80,

  // ----------------------------------------------------------
  // 2. tabWidth  ——  缩进宽度（空格数）
  // ----------------------------------------------------------
  //  每个缩进层级使用的空格数量。
  //  默认值：2
  //  注意：仅当 useTabs 为 false 时生效。
  tabWidth: 2,

  // ----------------------------------------------------------
  // 3. useTabs  ——  是否使用 Tab 缩进
  // ----------------------------------------------------------
  //  true：使用 tab 字符缩进。
  //  false：使用空格缩进（数量由 tabWidth 决定）。
  //  默认值：false
  useTabs: false,

  // ----------------------------------------------------------
  // 4. semi  ——  是否在语句末尾添加分号
  // ----------------------------------------------------------
  //  true：所有语句末尾都加分号。
  //  false：仅在可能导致 ASI（自动分号插入）错误时加分号。
  //  默认值：true
  semi: true,

  // ----------------------------------------------------------
  // 5. singleQuote  ——  是否使用单引号
  // ----------------------------------------------------------
  //  true：使用单引号（'string'）。
  //  false：使用双引号（"string"）。
  //  默认值：false
  //  注意：JSX 中的引号由 jsxSingleQuote 单独控制。
  singleQuote: false,

  // ----------------------------------------------------------
  // 6. quoteProps  ——  对象属性名的引号策略
  // ----------------------------------------------------------
  //  "as-needed"：仅在需要时添加引号（默认）。
  //  "consistent"：如果对象中任一属性需要引号，则所有属性都加引号。
  //  "preserve"：尊重输入代码中的引号使用方式。
  //  默认值："as-needed"
  quoteProps: 'as-needed',

  // ----------------------------------------------------------
  // 7. jsxSingleQuote  ——  JSX 中是否使用单引号
  // ----------------------------------------------------------
  //  true：JSX 属性使用单引号（<div className='box' />）。
  //  false：JSX 属性使用双引号（<div className="box" />）。
  //  默认值：false
  jsxSingleQuote: false,

  // ----------------------------------------------------------
  // 8. trailingComma  ——  尾随逗号
  // ----------------------------------------------------------
  //  在多行结构（数组、对象、函数参数等）最后一项后是否添加逗号。
  //  可选值：
  //    "none"   ：不添加尾随逗号。
  //    "es5"    ：在 ES5 有效位置添加（对象、数组等），默认值。
  //    "all"    ：尽可能在所有位置添加（包括函数参数和调用）。
  //  默认值："all"（Prettier 3.x 起） / "es5"（Prettier 2.x）
  //  注意：TypeScript 中开启 "all" 需要 TS 2.7+。
  trailingComma: 'all',

  // ----------------------------------------------------------
  // 9. bracketSpacing  ——  对象括号内的空格
  // ----------------------------------------------------------
  //  true：{ foo: bar }（括号内侧有空格）。
  //  false：{foo: bar}（括号内侧无空格）。
  //  默认值：true
  bracketSpacing: true,

  // ----------------------------------------------------------
  // 10. bracketSameLine  ——  HTML/JSX 标签右尖括号位置
  // ----------------------------------------------------------
  //  控制多行 HTML/JSX/Angular/Vue 元素的结束 `>` 位置。
  //  true：将 `>` 放在最后一行的末尾（与属性同行）。
  //    <button
  //      className="btn"
  //      onClick={handler}>
  //      Click me
  //    </button>
  //  false：将 `>` 单独放在新行（默认）。
  //    <button
  //      className="btn"
  //      onClick={handler}
  //    >
  //      Click me
  //    </button>
  //  默认值：false
  //  历史名称：--jsx-bracket-same-line (已废弃，请使用此选项)
  bracketSameLine: false,

  // ----------------------------------------------------------
  // 11. arrowParens  ——  箭头函数参数括号
  // ----------------------------------------------------------
  //  "always"：始终包裹括号。 (x) => x
  //  "avoid" ：尽可能省略括号。 x => x
  //  默认值："always"
  arrowParens: 'always',

  // ----------------------------------------------------------
  // 12. rangeStart  ——  格式化范围起始位置（字符偏移）
  // ----------------------------------------------------------
  //  仅格式化文件中从该偏移量开始的部分。
  //  与 rangeEnd 配合使用可实现局部格式化。
  //  默认值：0（从文件开头）
  //  注意：通常通过编辑器插件或 CLI 参数使用，很少写入配置文件。
  // rangeStart: 0,

  // ----------------------------------------------------------
  // 13. rangeEnd  ——  格式化范围结束位置（字符偏移）
  // ----------------------------------------------------------
  //  仅格式化文件中到该偏移量为止的部分。
  //  默认值：Infinity（到文件末尾）
  //  注意：通常通过编辑器插件或 CLI 参数使用，很少写入配置文件。
  // rangeEnd: Infinity,

  // ----------------------------------------------------------
  // 14. parser  ——  指定解析器
  // ----------------------------------------------------------
  //  强制 Prettier 使用指定的解析器，而非根据文件扩展名自动推断。
  //  可选值（部分常用）：
  //    "babel"          - JavaScript / JSX
  //    "typescript"     - TypeScript / TSX
  //    "flow"           - Flow
  //    "json"           - JSON
  //    "json5"          - JSON5
  //    "json-stringify" - JSON.stringify 输出
  //    "css"            - CSS
  //    "scss"           - SCSS
  //    "less"           - Less
  //    "html"           - HTML
  //    "vue"            - Vue SFC
  //    "angular"        - Angular 模板
  //    "markdown"       - Markdown
  //    "mdx"            - MDX
  //    "yaml"           - YAML
  //    "graphql"        - GraphQL
  //  默认值：无（自动推断）
  //  注意：通常不需要手动设置，仅在 overrides 或特殊场景使用。
  // parser: 'typescript',

  // ----------------------------------------------------------
  // 15. filepath  ——  文件路径（用于推断解析器）
  // ----------------------------------------------------------
  //  当从 stdin 输入时，用于告诉 Prettier 文件路径以推断解析器和输出格式。
  //  默认值：无
  //  注意：仅 CLI 使用，不写入配置文件。
  // filepath: 'src/index.ts',

  // ----------------------------------------------------------
  // 16. requirePragma  ——  是否要求 @prettier / @format 标记
  // ----------------------------------------------------------
  //  true：仅格式化文件顶部包含 @prettier 或 @format 注释的文件。
  //  false：格式化所有文件（默认）。
  //  默认值：false
  //  适用场景：逐步引入 Prettier 到大型项目中，只格式化标记过的文件。
  requirePragma: false,

  // ----------------------------------------------------------
  // 17. insertPragma  ——  格式化后是否插入 @format 标记
  // ----------------------------------------------------------
  //  true：在文件顶部插入 /** @format */ 注释，标记该文件已被 Prettier 格式化。
  //  false：不插入标记（默认）。
  //  默认值：false
  //  注意：与 requirePragma 配合使用，适合渐进式引入 Prettier。
  insertPragma: false,

  // ----------------------------------------------------------
  // 18. proseWrap  ——  Markdown 文本换行策略
  // ----------------------------------------------------------
  //  "always"    ：当超过 printWidth 时自动换行（默认）。
  //  "never"     ：永不换行，每段保持为一行。
  //  "preserve"  ：保持原样，不做任何换行处理。
  //  默认值："preserve"
  //  注意：仅影响 Markdown / MDX 文件中的散文段落。
  proseWrap: 'preserve',

  // ----------------------------------------------------------
  // 19. htmlWhitespaceSensitivity  ——  HTML 空白敏感度
  // ----------------------------------------------------------
  //  控制 HTML / Vue / Angular / JSX 文件中空白的处理方式。
  //  "css"     ：遵循 CSS display 属性值（默认）。块级元素周围保留空白，内联元素不保留。
  //  "strict"  ：所有标签周围的空白都被视为有意义的，不会删除。
  //  "ignore"  ：所有空白都被视为无意义的，可能被删除或修改。
  //  默认值："css"
  htmlWhitespaceSensitivity: 'css',

  // ----------------------------------------------------------
  // 20. vueIndentScriptAndStyle  ——  Vue 文件中 script/style 标签是否缩进
  // ----------------------------------------------------------
  //  true：<script> 和 <style> 标签内的内容会额外缩进一层。
  //    <script>
  //      export default {
  //        name: 'App'
  //      }
  //    </script>
  //  false：不缩进（默认）。
  //    <script>
  //    export default {
  //      name: 'App'
  //    }
  //    </script>
  //  默认值：false
  //  注意：仅对 Vue SFC 文件生效。
  vueIndentScriptAndStyle: false,

  // ----------------------------------------------------------
  // 21. endOfLine  ——  行尾换行符
  // ----------------------------------------------------------
  //  "lf"   ：仅使用 LF（\n），Linux/macOS 默认。
  //  "crlf" ：仅使用 CRLF（\r\n），Windows 默认。
  //  "cr"   ：仅使用 CR（\r），极少使用。
  //  "auto" ：自动检测并保持现有行尾风格（默认）。
  //  默认值："lf"（Prettier 3.x 起）/ "auto"（Prettier 2.x）
  //  建议：跨平台协作的项目统一设为 "lf"，配合 Git 的 core.autocrlf。
  endOfLine: 'lf',

  // ----------------------------------------------------------
  // 22. embeddedLanguageFormatting  ——  嵌入式语言格式化
  // ----------------------------------------------------------
  //  控制是否格式化嵌入在代码中的其他语言（如 HTML 中的 CSS/JS）。
  //  "auto"：自动格式化嵌入式代码（默认）。
  //  "off" ：不格式化嵌入式代码。
  //  默认值："auto"
  //  示例：JavaScript 模板字符串中的 CSS、HTML 中的 <style>/<script> 等。
  embeddedLanguageFormatting: 'auto',

  // ----------------------------------------------------------
  // 23. singleAttributePerLine  ——  单行单个属性
  // ----------------------------------------------------------
  //  true：HTML / Vue / JSX / Angular 元素中每个属性独占一行。
  //    <div
  //      id="app"
  //      class="container"
  //      data-value="1"
  //    />
  //  false：允许多个属性在同一行（默认）。
  //    <div id="app" class="container" data-value="1" />
  //  默认值：false
  //  注意：仅当元素超过 printWidth 时才会换行，不会强制单属性单行。
  //  注意：Prettier 3.x 新增选项。
  singleAttributePerLine: false,

  // ----------------------------------------------------------
  // 24. overrides  ——  覆盖配置
  // ----------------------------------------------------------
  //  为特定文件类型或路径模式提供不同的格式化选项。
  //  数组中的每个对象包含：
  //    files      ：glob 模式，匹配要覆盖的文件路径。
  //    options    ：覆盖的配置选项对象。
  //    excludeFiles：排除的 glob 模式（可选）。
  //  注意：JSON 格式不支持注释，若需使用 overrides 建议用 .prettierrc.js 或 .prettierrc.json5。
  overrides: [
    // 示例：为 JSON 文件使用不同的缩进
    // {
    //   files: '*.json',
    //   options: {
    //     tabWidth: 4,
    //     parser: 'json',
    //   },
    // },
    // 示例：为 Markdown 文件使用不同的 printWidth
    // {
    //   files: ['*.md', '*.mdx'],
    //   options: {
    //     proseWrap: 'always',
    //     printWidth: 100,
    //   },
    // },
    // 示例：为测试文件关闭分号
    // {
    //   files: ['**/*.test.js', '**/*.spec.js'],
    //   options: {
    //     semi: false,
    //   },
    // },
  ],

  // ----------------------------------------------------------
  // 25. plugins  ——  插件列表
  // ----------------------------------------------------------
  //  指定 Prettier 插件包名数组。
  //  插件可以提供额外的语言支持或格式化功能。
  //  默认值：[]
  //  示例：
  //    plugins: ['prettier-plugin-tailwindcss', 'prettier-plugin-organize-imports'],
  //  注意：JSON 格式不支持注释，若需使用 plugins 建议用 .prettierrc.js 或 .prettierrc.json5。
  // plugins: [],
};

// ============================================================
//  补充说明：
//  ──────────────────────────────────────────
//  1. 配置文件优先级（由高到低）：
//     CLI 参数 > 项目根目录配置 > 编辑器设置
//
//  2. 配置文件格式优先级（由高到低）：
//     package.json 中的 "prettier" 字段
//     .prettierrc（JSON / YAML / TOML）
//     .prettierrc.json / .prettierrc.json5
//     .prettierrc.yaml / .prettierrc.yml
//     .prettierrc.toml
//     prettier.config.js / .prettierrc.js（CommonJS Module）
//     prettier.config.mjs / .prettierrc.mjs（ES Module）
//     prettier.config.cjs（CommonJS Module）
//
//  3. 忽略文件：
//     在项目根目录创建 .prettierignore 文件，
//     语法与 .gitignore 相同，用于排除不需要格式化的文件。
//
//  4. 编辑器集成：
//     VS Code：安装 Prettier 扩展，设置默认格式化器。
//     WebStorm：内置支持，在设置中启用即可。
//
//  5. 与 ESLint 配合：
//     使用 eslint-config-prettier 关闭与 Prettier 冲突的 ESLint 规则。
//     使用 eslint-plugin-prettier 将 Prettier 作为 ESLint 规则运行（可选）。
// ============================================================